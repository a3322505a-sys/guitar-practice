"""Generate app phrases from the reviewed PDF transcription. Never reads a GP/MIDI file.

The JSON retains written events, ties, PDF coordinates and exact selection windows.
Only ties are merged; selection padding is explicit and is not source notation.
"""
import json,copy
import re
from pathlib import Path
from song_assets.common import positions
from song_assets.pdf import validate_reviewed_pdf

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'scripts/score-data/your-trip.json'
OUT=ROOT/'app/src/main/java/com/a3322505a/guitarlearning/practice/YourTrip.kt'
def q(value): return json.dumps(value,ensure_ascii=False)
def expression(e):
    xp={}
    if 'grace' in e:
        g=e['grace'];xp[g['string']]=[f'grace=Grace({g["fret"]},kind=Technique.{g["kind"]})']
    if 'bend' in e:
        b=e['bend'];xp.setdefault(b['string'],[]).append('bend=listOf('+','.join(f'PitchPoint({float(t)},{float(v)})' for t,v in b['points'])+')')
    return 'mapOf('+','.join(f'{s} to StringExpression('+','.join(values)+')' for s,values in sorted(xp.items()))+')'
def generate(data_path=DATA, output_root=ROOT, object_name='YourTrip', track_name='od.guit.', include_events=False):
    if not re.fullmatch(r'[A-Z][A-Za-z0-9_]*',object_name): raise ValueError('invalid Kotlin object name')
    data=json.loads(Path(data_path).read_text(encoding='utf8'))
    validate_reviewed_pdf(data)
    bars={b['number']:b for b in data['bars']}
    lines=['package com.a3322505a.guitarlearning.practice','','import com.a3322505a.guitarlearning.music.Position','',
           '// Generated by scripts/generate-your-trip.py from the reviewed PDF transcription.',
           f'// Original PDF SHA-256: {data["sha256"]}', f'object {object_name} {{',
           '    val phrases=listOf('+','.join(p['id'].split('-',1)[-1].lower().replace('-','_')+'()' for p in data['parts'])+')']
    summary=[]
    for p in data['parts']:
        first,last=p['first'],p['last'];length=(last-first+1)*48;end=(last-first)*48+p['end']
        events=[];links=[];triplets=[];written=0;padding=[]
        for n in range(first,last+1):
            for original in bars[n]['events']:
                e=copy.deepcopy(original);t=(n-first)*48+e['tick'];d=e['duration'];written+=1
                assert t+d<=length
                if t<p['start'] or t>=end:
                    assert t+d<=p['start'] or t>=end,'selection bisects a source note'
                    e=dict(notes=[],dead=[],tied=[],duration=d,padding=True)
                    padding.append([t,t+d])
                else:
                    for link in e.get('legato',[]): links.append([(n-first)*48+link['source'],t,link['string'],link['kind']])
                    if e.get('triplet') and e['tick']%6==0: triplets.append([t,2])
                if e.get('tied'):
                    assert events and e['tied']==[s for s,f in e['notes']] and not e['dead']
                    prev=events[-1]
                    assert prev['notes']==e['notes'] and prev['at']+prev['duration']==t,(p['id'],n,t)
                    prev['duration']+=d
                else:
                    e['at']=t;e['bar']=n
                    if e.get('ringToBarEnd'): e['ringEnd']=(e['ringToBarEnd']-first+1)*48
                    if e.get('padding') and events and events[-1].get('padding') and events[-1]['bar']==n:
                        events[-1]['duration']+=d
                    else: events.append(e)
        assert events[0]['at']==0 and events[-1]['at']+events[-1]['duration']==length
        assert all(a['at']+a['duration']==b['at'] for a,b in zip(events,events[1:]))
        assert all(any(e['at']==s for e in events) and any(e['at']==t for e in events) for s,t,_,_ in links)
        function=p['id'].split('-',1)[-1].lower().replace('-','_')
        passage=f'{first}–{last} 小节'
        if p['start'] or p['end']!=48: passage+=' · 含句界留空'
        lines += [f'    private fun {function}() = Phrase(',f'        id={q(p["id"])},title={q(p["title"])},category="歌曲完整乐句",passage={q(passage)},',
            f'        source={q(data["source"]+" · "+track_name+" · 第"+str(bars[first]["page"])+"–"+str(bars[last]["page"])+"页")},sourceBpm={data["bpm"]},',
            f'        difficulty="进阶（建议慢练）",technique={q(p["technique"])},conditions="标准调弦 · 变调夹{data["capo"]}品",',
            f'        goal={q(p["goal"])},suggestedBpm={p["bpm"]},use={q(p["use"])},',
            '        sequence=Sequence(events=listOf(']
        previousBar=None
        for e in events:
            if e['bar']!=previousBar: lines.append(f'            // PDF bar {e["bar"]}');previousBar=e['bar']
            args=[str(e['at']),str(e['duration']),positions(e['notes'])]
            if e['dead']: args.append('deadStrings=setOf('+','.join(map(str,e['dead']))+')')
            if e.get('legato'): args.append('pick=Pick.NONE')
            if e.get('grace') or e.get('bend'): args.append('stringExpression='+expression(e))
            if e.get('vibrato'): args.append('vibrato=true')
            if e.get('strum'): args.append('strum=true')
            if e.get('ringEnd'): args+=['ring=true',f'ringEndTick={e["ringEnd"]}']
            if e.get('velocity'): args.append(f'velocity={e["velocity"]}f')
            if data['sha256']=='3293c583569de637fa69396bd3280a483e3d1cef42a3645c7c31e03349406bc7' and e['bar']==115 and e.get('velocity')==.65: args.append('dynamicMark="渐强"')
            lines.append('            Event('+','.join(args)+'),'+(' // Practice padding outside selected phrase.' if e.get('padding') else ''))
        explain=p['description']+f' 标准调弦，变调夹{data["capo"]}品；数字为相对品位。推弦、装饰及连续连奏为采样示范近似。'
        lines += [f'        ),length={length},originalBar={first-1},capoFret={data["capo"]},explanation={q(explain)},',
            '        links=listOf('+','.join(f'Legato({s},{t},{string},Technique.{kind})' for s,t,string,kind in links)+'),',
            '        tuplets=listOf('+','.join(f'Tuplet({t},{u})' for t,u in triplets)+')),','    )']
        summary.append(dict(id=p['id'],sourceWindow=[first,p['start'],last,p['end']],events=len(events),writtenEvents=written,links=len(links),triplets=len(triplets),padding=padding))
        if include_events:
            summary[-1]['eventsData']=[dict(tick=e['at'],duration=e['duration'],positions=e['notes'],deadStrings=e['dead'],
                pick='NONE' if e.get('legato') else 'DEFAULT',velocity=e.get('velocity',1.0),
                expression={k:v for k,v in e.items() if k not in ('at','duration','notes','dead','bar','padding')},
                practicePadding=e.get('padding',False),sourceBar=e['bar']) for e in events]
            summary[-1]['linksData']=links;summary[-1]['tupletsData']=triplets
    lines += ['}','']
    (output_root/f'app/src/main/java/com/a3322505a/guitarlearning/practice/{object_name}.kt').write_text('\n'.join(lines),encoding='utf8')
    dest=output_root/'work/your-trip-v72/generation.json';dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(json.dumps(summary,indent=2),encoding='utf8')
    for s in summary: print(s['id'],s['sourceWindow'],s['events'],'events',s['links'],'links')
    return summary

if __name__=='__main__':
    generate()
