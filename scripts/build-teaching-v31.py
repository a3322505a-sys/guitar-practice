class Builder:
    def __init__(self):
        self.score=dict(documentId='teaching-v31',measures=[],tracks=[dict(id='guitar',name='吉他',openStringMidi=OPEN)],
            voices=[dict(id='voice',trackId='guitar',events=[])],tuplets=[],relations=[],tempos=[dict(at=rat(0),beatUnit=rat(1),bpm=60)],
            dynamics=[],swing=[],form={},voicings=[],harmonies=[])
        self.practices=[]; self.proofs=[]
    def voicing(self,name,capo=0,dual=False):
        quality,root,frets,fingers=CHORDS[name]; frets=list(reversed(frets)); fingers=list(reversed(fingers))
        token='chord-'+str(list(CHORDS).index(name))+('-capo2' if capo else '')+('-dual' if dual else '')
        if any(v['id']==token for v in self.score['voicings']): return token
        if dual:
            strings=[i for i in range(5,-1,-1) if frets[i]>=0][:2]
            frets=[f if i in strings else -1 for i,f in enumerate(frets)]
            fingers=[f if i in strings else 0 for i,f in enumerate(fingers)]
        track='guitar-capo2' if capo else 'guitar'
        if capo and not any(t['id']==track for t in self.score['tracks']):
            self.score['tracks'].append(dict(id=track,name='Capo 2 吉他',openStringMidi=OPEN,capo=2))
            self.score['voices'].append(dict(id='voice-capo2',trackId=track,events=[]))
        sounding=NAMES[(root+capo)%12]+{'MAJOR':'','MINOR':'m','MAJOR_SEVENTH':'maj7','ADD_NINE':'add9','POWER':'5','SUS_TWO':'sus2','SUS_FOUR_NO_FIVE':'sus4(no5)','MINOR_SEVENTH_NO_FIVE':'m7(no5)'}[quality]
        if '/' in name: sounding += '/'+NAMES[(NAMES.index(name.split('/')[1])+capo)%12]
        v=dict(id=token,name=name,trackId=track,frets=frets,fingers=fingers,quality=quality,
            teaching=dict(root=(root+capo)%12,soundingName=sounding,group='基础和弦',source='V3.1 已核验配法'))
        third=next(((root+capo+i)%12 for i in QUALITIES[quality] if i in (3,4)),None)
        if third is not None: v['teaching']['third']=third
        if name in BARRES: v['barres']=BARRES[name]
        self.score['voicings'].append(v); return token
    def phrase(self,id,title,route,module,key=None,step=F(1),goal='',fingerings=None,variant=None,capo=0,dual=False,metadata=None):
        # route entries are physical (string,fret), a chord name, None/rest, or (positions,duration,articulation).
        track='guitar-capo2' if capo else 'guitar'; events=[]; at=F(0); bar=0; harmonies=[]; assignments=[]
        last_harmony=None
        for index,item in enumerate(route):
            duration=step; art={}
            if isinstance(item,dict): duration=F(item.get('duration',step)); art=item.get('articulation',{}); item=item.get('positions')
            chord=item if isinstance(item,str) else None
            if chord:
                vid=self.voicing(chord,capo,dual); v=next(v for v in self.score['voicings'] if v['id']==vid)
                positions=[(i+1,f) for i,f in enumerate(v['frets']) if f>=0]
                if chord!=last_harmony:
                    harmonies.append(dict(id=id+'-h-'+str(index),measureId=id+'-m-'+str(bar),onset=rat(at%4),name=chord,voicingId=vid)); last_harmony=chord
                art=dict(pick='down',strumDelayMs=12,**art)
            elif item is None: positions=[]
            elif isinstance(item,tuple): positions=[item]
            else: positions=item
            assert 0<duration<=4-at%4,(id,index,'event crosses bar')
            event_id=id+'-e-'+str(index)
            notes=[dict(id=event_id+'-s-'+str(s),string=s,fret=f,midi=OPEN[s-1]+capo+f) for s,f in positions]
            written=next((dict(baseDenominator=base,dots=dots) for base in (1,2,4,8,16,32,64) for dots in range(4)
                if F(4,base)*sum(F(1,2**d) for d in range(dots+1))==duration),None)
            assert written,(id,duration)
            events.append(dict(id=event_id,measureId=id+'-m-'+str(bar),onset=rat(at%4),duration=rat(duration),written=written,notes=notes,articulation=art))
            for n in notes:
                finger = (v['fingers'][n['string']-1] if chord else (fingerings or {}).get((n['string'],n['fret']), n['fret'] if n['fret'] in range(1,5) else None))
                if n['fret']>0 and finger:
                    assignments.append(dict(sourceNoteId=n['id'],finger=finger,source='V3.1 逐弦配指核验'))
            at+=duration; bar=int(at//4)
        if at%4:
            remainder=4-at%4
            # Fill with separate quarters/eighths so every written value stays exact.
            while remainder:
                duration=min(F(1),remainder); idx=len(events)
                events.append(dict(id=id+'-rest-'+str(idx),measureId=id+'-m-'+str(int(at//4)),onset=rat(at%4),duration=rat(duration),written=dict(baseDenominator=int(4/duration)),notes=[]))
                at+=duration; remainder-=duration
        measures=[dict(id=id+'-m-'+str(i),label=str(i+1),meter=dict(numerator=4,denominator=4,beatGroups=[1]*4),actualDuration=rat(4)) for i in range(int(at/4))]
        end=sum(q(m['actualDuration']) for m in self.score['measures'])+at
        for h in harmonies: h['validUntil']=rat(end)
        self.score['measures']+=measures; self.score['harmonies']+=harmonies
        next(v for v in self.score['voices'] if v['trackId']==track)['events']+=events
        lesson=dict(module=module,**(metadata or {}))
        if key: lesson['key']=dict(tonic=key[0],scale=key[1])
        p=dict(id=id,title=title,goal=goal or '按节拍完整弹奏，放松双手，手动调速。',mainTrackId=track,mixTrackIds=[track],
            segments=[dict(start=dict(measureId=measures[0]['id']),end=dict(measureId=measures[-1]['id'],offset=rat(4)))],
            suggestedTempo=60,tempoMode='fixed',order=len(self.practices),tags=[module],lesson=lesson,noteFingerings=assignments,
            teaching=dict(category={'FOUNDATIONS':'基础启蒙','CHORDS':'和弦教学','SCALES':'音阶教学','APPLICATION':'综合应用'}[module],passage=str(len(measures))+' 小节',source='原创教学短句 · V3.1',use={'FOUNDATIONS':'基础启蒙','CHORDS':'和弦教学','SCALES':'音阶教学','APPLICATION':'综合应用'}[module],explanation=goal or title))
        if variant: p.update(familyId=variant,variantOf=variant,visibility='variant'); p['teaching']['version']='双音版' if dual else '律动版'
        else: p['teaching']['version']='原谱版'
        self.practices.append(p)
        self.proofs.append(dict(id=id,events=len(events),notes=sum(len(e['notes']) for e in events),quarters=str(at)))
        return p

